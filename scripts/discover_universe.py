"""CLI: inspect — or write to the universe registry — the discoverable symbol set.

Enumerates every USD-M perp that ever traded (incl. delisted where the venue allows)
intersected with spot — the set ``backfill --universe`` fetches. ``--write`` regenerates
``config/universe/{source}.yaml`` from the discovery: the universe file is the instrument
REGISTRY OF RECORD for every strategy (strategies resolve their universe from it; the lake
only gates data availability), so it must contain every instrument in use, not a hand-kept
sample. Hand-set fields on existing entries (tick_size, subsector, ...) survive regeneration;
discovered facts (status, listed, delisted) always win.

    uv run python -m scripts.discover_universe --source binance            # inspect
    uv run python -m scripts.discover_universe --source binance --write    # update registry
"""

from __future__ import annotations

import argparse

import pandas as pd
import yaml

from src.common import config as cfg
from src.common import paths

_HEADER = """\
# Instrument universe for {source} — the registry of record for every instrument used by
# any strategy in this repo (one entry per (symbol, market), keyed `{{symbol}}_{{spot|perp}}`).
#
# GENERATED by `scripts.discover_universe --source {source} --write` from the venue's own
# instrument metadata (spot-paired perps, delisted included where the venue allows); do not
# hand-enumerate. Hand-set fields on existing entries (tick_size, subsector, ...) survive
# regeneration; discovered facts (status, listed, delisted) always win. Strategies resolve
# `universe: all` FROM THIS FILE (intersected with lake data availability); what data exists
# is still discovered via query, and what to fetch lives in config/data/.
"""


def _ms_to_date(ms) -> str | None:
    if ms is None or pd.isna(ms) or not ms:
        return None
    return str(pd.Timestamp(int(ms), unit="ms").date())


def _entries(source: str, df: pd.DataFrame, quote: str) -> dict[str, dict]:
    """Two registry entries (perp + spot leg) per spot-paired coin, delisted included."""
    out: dict[str, dict] = {}
    for sym, r in df[df["has_spot"]].sort_index().iterrows():
        base = str(r.get("base_asset") or r.get("coin", sym)).lower()
        cur = str(r.get("quote_asset") or quote)
        common = {"base_asset": base, "quote_asset": cur.lower(), "currency": cur.upper(),
                  "status": str(r["status"]), "sector": "crypto", "session": "crypto_24_7"}
        listed = _ms_to_date(r.get("onboard_ms") or r.get("launch_ms") or r.get("list_ms"))
        delisted = _ms_to_date(r.get("delivery_ms"))

        perp = {"symbol": sym, "asset_type": "perps", **common}
        if listed:
            perp["listed"] = listed
        if delisted:
            perp["delisted"] = delisted
        if source == "okx":
            perp["inst_id"] = str(r["inst_id"])

        if source == "hyperliquid":                      # spot leg is a different lake symbol
            spot_sym = r.get("spot_symbol")
            spot = {"symbol": spot_sym, "asset_type": "spot", **common,
                    "pair_index": str(r["spot_pair"]), "perp_symbol": sym}
            out[f"{sym}_perp"] = perp
            out[f"{spot_sym}_spot"] = spot
            continue
        spot = {"symbol": sym, "asset_type": "spot", **common}
        if source == "okx":
            spot["inst_id"] = f"{base.upper()}-{cur.upper()}"
        out[f"{sym}_perp"] = perp
        out[f"{sym}_spot"] = spot
    return out


def _write_registry(source: str, generated: dict[str, dict]) -> None:
    path = paths.CONFIG_DIR / "universe" / f"{source}.yaml"
    existing: dict = {}
    if path.is_file():
        existing = cfg.load_config(f"universe/{source}.yaml")
    sessions = existing.get("sessions") or {"crypto_24_7": "24/7 continuous, no daily halt, UTC"}

    merged: dict[str, dict] = {}
    for key, gen in generated.items():
        old = existing.get(key)
        if isinstance(old, dict):                        # hand-set fields survive; facts win
            kept = {k: v for k, v in old.items() if k not in ("status", "listed", "delisted")}
            merged[key] = {**gen, **kept,
                           **{f: gen[f] for f in ("status", "listed", "delisted") if f in gen}}
        else:
            merged[key] = gen
    manual = [k for k in existing if k != "sessions" and k not in generated]
    for key in manual:                                   # never drop a hand-added instrument
        merged[key] = existing[key]
    if manual:
        print(f"kept {len(manual)} entries not in discovery (hand-added or venue-erased): "
              f"{manual[:8]}{'...' if len(manual) > 8 else ''}")

    body = yaml.safe_dump({"sessions": sessions}, sort_keys=False, allow_unicode=True)
    body += "\n" + yaml.safe_dump(dict(sorted(merged.items())), sort_keys=False,
                                  allow_unicode=True, width=100)
    path.write_text(_HEADER.format(source=source) + "\n" + body, encoding="utf-8")
    print(f"wrote {path} — {len(merged)} entries "
          f"({sum(1 for v in merged.values() if v.get('asset_type') == 'perps')} perp legs)")


def main() -> None:
    p = argparse.ArgumentParser(description="Inspect or write the discoverable symbol set.")
    p.add_argument("--source", default="binance")
    p.add_argument("--quote", default="USDT")
    p.add_argument("--write", action="store_true",
                   help="regenerate config/universe/{source}.yaml from discovery")
    args = p.parse_args()
    if args.source == "hyperliquid":
        from src.data.fetching.hyperliquid import instruments
        df = instruments.discover()          # USDC-only venue; --quote does not apply
        quote = "USDC"
    elif args.source == "binance":
        from src.data.fetching.binance import instruments
        df = instruments.discover(args.quote)
        quote = args.quote
    elif args.source == "bybit":
        from src.data.fetching.bybit import instruments
        df = instruments.discover(args.quote)
        quote = args.quote
    elif args.source == "okx":
        from src.data.fetching.okx import instruments
        print("warning: okx cannot enumerate delisted instruments — universe is survivors-only")
        df = instruments.discover(args.quote)
        quote = args.quote
    elif args.source == "mexc":
        from src.data.fetching.mexc import instruments
        print("warning: mexc cannot enumerate delisted instruments — universe is survivors-only")
        df = instruments.discover(args.quote)
        quote = args.quote
    else:
        raise SystemExit(f"discovery not implemented for source {args.source!r}")
    print(df.head().to_string())
    print(f"\n{len(df)} perps | {int(df['has_spot'].sum())} tradeable (with spot) | "
          f"{int((df['status'] == 'delisted').sum())} delisted")
    if args.write:
        _write_registry(args.source, _entries(args.source, df, quote))


if __name__ == "__main__":
    main()
